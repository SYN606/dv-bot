/**
 * Fast in-memory interaction counter between user pairs
 * Key: `${guildId}:${minUserId}:${maxUserId}:${action}` -> Number
 */
const interactionTracker = new Map<string, number>();
const MAX_TRACKER_SIZE = 10000;

export function getAndIncrementInteraction(guildId, userAId, userBId, action) {
  if (!guildId || !userAId || !userBId) return { count: 1 };
  const pair = [String(userAId), String(userBId)].sort().join(":");
  const key = `${guildId}:${pair}:${action.toLowerCase()}`;

  const current = (interactionTracker.get(key) || 0) + 1;
  if (interactionTracker.size >= MAX_TRACKER_SIZE) {
    // Evict oldest 2000 entries
    let count = 0;
    for (const k of interactionTracker.keys()) {
      interactionTracker.delete(k);
      if (++count > 2000) break;
    }
  }
  interactionTracker.set(key, current);
  return { count: current };
}

export function formatInteractionFooter(count, actionName) {
  if (count <= 1) {
    return `First time sharing a ${actionName}! ✨`;
  }
  const suffix =
    count === 2
      ? "2nd"
      : count === 3
      ? "3rd"
      : `${count}th`;
  return `That's their ${suffix} ${actionName} together! 💕`;
}

